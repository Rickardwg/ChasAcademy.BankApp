namespace BankApp.Enums;

public enum ErrorMessages
{
    /// <summary>
    /// Indicates that the user's account has been locked.
    /// </summary>
    LockedAccount,

    /// <summary>
    /// Indicates that the specified user could not be found.
    /// </summary>
    UserNotFound,

    /// <summary>
    /// Indicates that the selected option is invalid.
    /// </summary>
    InvalidOption,

}
